import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { registerUser, loginUser, me } from '../controllers/authController.js';
import * as analysis from '../controllers/analysisController.js';
import * as dashboard from '../controllers/dashboardController.js';
import * as user from '../controllers/userController.js';
import * as admin from '../controllers/adminController.js';
import { protect, adminOnly } from '../middleware/auth.js';

const router = Router();
const authLimiter = rateLimit({ windowMs: 15*60*1000, limit: 30, standardHeaders: 'draft-7', legacyHeaders: false });
router.get('/health', (req,res) => res.json({ success: true, service: 'TrustLens API', timestamp: new Date().toISOString() }));
router.post('/auth/register', authLimiter, registerUser);
router.post('/auth/login', authLimiter, loginUser);
router.get('/auth/me', protect, me);
router.use(protect);
router.post('/analyses', analysis.create);
router.get('/analyses', analysis.list);
router.get('/analyses/:id/status', analysis.status);
router.get('/analyses/:id', analysis.getOne);
router.delete('/analyses/:id', analysis.remove);
router.get('/dashboard/overview', dashboard.overview);
router.get('/dashboard/activity', dashboard.activity);
router.get('/users/me', (req,res) => res.json({ success: true, data: { user: { id: req.user._id, name: req.user.name, email: req.user.email, role: req.user.role, createdAt: req.user.createdAt } } }));
router.put('/users/me', user.updateMe);
router.use('/admin', adminOnly);
router.get('/admin/dashboard', admin.dashboard);
router.get('/admin/users', admin.listUsers);
router.get('/admin/sources', admin.listSources);
router.post('/admin/sources', admin.createSource);
router.put('/admin/sources/:id', admin.updateSource);
router.delete('/admin/sources/:id', admin.deleteSource);
export default router;
